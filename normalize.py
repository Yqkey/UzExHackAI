def canon_product(name):
    n = name.lower().replace("ё", "е")
    for pat, canon in PRODUCT_RULES:
        if re.search(pat, n):
            return canon
    return None

SORT_RE = re.compile(r"(?<![\w])(высш\w*|в/с|первый|второй|третий|iii|ii|i|[123])[\s\-]*сорт\w*", re.I)
CLASS_RE = re.compile(r"(?<![\w])(iv|iii|ii|i|[1-4])[\s\-]*класс\w*", re.I)
SORT_MAP = {"первый":"1","i":"1","1":"1","второй":"2","ii":"2","2":"2","третий":"3","iii":"3","3":"3"}
CLASS_MAP = {"i":"1","1":"1","ii":"2","2":"2","iii":"3","3":"3","iv":"4","4":"4"}

def norm_sort(s):
    if not s: return None
    m = SORT_RE.search(s)
    if m:
        t = m.group(1).lower()
        return "высший" if t.startswith("высш") or t == "в/с" else SORT_MAP[t]
    if re.search(r"высш|^в/с$", s.lower()): return "высший"
    return s.strip().lower()

def norm_class(s):
    if not s: return None
    m = CLASS_RE.search(s)
    if m: return CLASS_MAP[m.group(1).lower()]
    return s.strip().upper()          # напр. А500С

def norm_token(s):                      # марка/размер: без пробелов, в верхнем регистре
    return None if not s else re.sub(r"\s+", "", s).upper().replace("Ø", "Ø")

def norm_type(s):
    return None if not s else s.strip().lower()

